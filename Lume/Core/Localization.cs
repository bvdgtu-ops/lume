    /// <summary>Строка на текущем языке; формат-подстановки — через string.Format.</summary>
    public static string T(string key) =>
        (Lang == "en" ? En : Ru).TryGetValue(key, out var v) ? v : key;

    public static void Set(string lang)
    {
        var next = lang == "en" ? "en" : "ru";
        if (next == Lang) return;
        Lang = next;
        LanguageChanged?.Invoke();
    }
